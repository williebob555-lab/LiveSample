// ============================================================================
// The instrument model.
//
// This is the source of truth. Every exporter (SFZ, DecentSampler, Ableton,
// LivePatch, bare WAV folder) is a lossy projection of what is described here,
// so the model is deliberately the *union* of what those targets can express
// rather than the intersection. Exporters declare what they drop; the UI warns
// before writing rather than after.
//
//   Instrument
//     └─ Articulation[]        switchable variants (sustain / staccato / pizz)
//          └─ Group[]          shared playback behaviour + round-robin rules
//               └─ Zone[]      one sample placed in key/velocity space
//
// Samples live in a flat pool on the instrument and are referenced by id, so
// the same take can be used by several zones without duplication.
// ============================================================================

export type Midi = number; // 0..127

// ---------------------------------------------------------------------------
// Samples (the take pool)
// ---------------------------------------------------------------------------

/** What the analyser worked out about a take, all optional until it runs. */
export interface SampleAnalysis {
  /** Detected pitch as a MIDI note, or null when unpitched/undetectable. */
  rootMidi?: Midi | null;
  /** Deviation from that note in cents (-50..50). */
  cents?: number;
  /** 0..1 — YIN aperiodicity inverted. Below ~0.6 treat the pitch as a guess. */
  confidence?: number;
  peakDb?: number;
  rmsDb?: number;
  /** First frame with real signal (transient-preserving, includes pre-roll). */
  onsetFrame?: number;
  /** Frame where the tail drops below the noise floor for good. */
  tailFrame?: number;
  /** Estimated noise floor in dBFS, from the quietest window. */
  noiseFloorDb?: number;
}

/** Where a take came from, so capture sessions can be resumed and audited. */
export interface CaptureMeta {
  /** The note the capture session asked for (may differ from detected pitch). */
  targetMidi?: Midi;
  /** 1-based velocity layer index within the session's layer plan. */
  velLayer?: number;
  /** 1-based round-robin index. */
  rrIndex?: number;
  articulationId?: string;
  micId?: string;
  takenAt?: number;
}

export interface Sample {
  id: string;
  name: string;
  /** Absolute path when the file lives on disk (Electron). */
  path?: string;
  sampleRate: number;
  channels: number;
  frames: number;
  analysis: SampleAnalysis;
  capture: CaptureMeta;
  /** True once cleanup (trim/normalise/denoise) has been applied and baked. */
  processed?: boolean;
  /** Set when this take was generated by repitching another sample. */
  derivedFrom?: { sampleId: string; semitones: number; formantPreserved: boolean };
}

// ---------------------------------------------------------------------------
// Zones
// ---------------------------------------------------------------------------

export type LoopMode = 'off' | 'forward' | 'pingpong' | 'sustain';

export interface Loop {
  mode: LoopMode;
  /** Frame offsets into the sample. */
  start: number;
  end: number;
  /** Crossfade length in frames, applied symmetrically around the splice. */
  crossfade: number;
}

export interface Zone {
  id: string;
  sampleId: string;
  /** Which mic bus this zone feeds; undefined = the single default bus. */
  micId?: string;

  keyLow: Midi;
  keyHigh: Midi;
  rootKey: Midi;

  velLow: number; // 1..127
  velHigh: number;

  /** Round-robin slot. Zones sharing key+vel space are cycled by rrIndex. */
  rrIndex: number;

  tuneCents: number;
  gainDb: number;
  pan: number; // -1..1

  /** Playback window into the sample, in frames. */
  startFrame: number;
  endFrame: number;
  loop: Loop;

  /** Amplitude fades at the window edges, in frames. */
  fadeInFrames: number;
  fadeOutFrames: number;
}

// ---------------------------------------------------------------------------
// Groups
// ---------------------------------------------------------------------------

export type TriggerMode = 'attack' | 'release' | 'legato';
export type RoundRobinMode = 'off' | 'sequential' | 'random' | 'randomNoRepeat';
export type FilterType = 'off' | 'lowpass' | 'highpass' | 'bandpass';

export interface Envelope {
  attack: number; // seconds
  decay: number;
  sustain: number; // 0..1
  release: number;
}

export interface FilterSettings {
  type: FilterType;
  cutoff: number; // Hz
  resonance: number; // Q
  /** Envelope depth in semitone-equivalent cutoff octaves (-4..4). */
  envAmount: number;
  /** 0..1 — how much the played note tracks cutoff. */
  keyTrack: number;
  /** 0..1 — how much velocity opens the filter. */
  velAmount: number;
}

export interface Group {
  id: string;
  name: string;
  articulationId: string;
  trigger: TriggerMode;
  roundRobin: RoundRobinMode;
  /** Notes in the same choke group cut each other off (hi-hats, mutes). */
  chokeGroup: number;
  gainDb: number;
  pan: number;
  ampEnv: Envelope;
  filter: FilterSettings;
  filterEnv: Envelope;
  /** 0..1 — how strongly velocity drives level. 1 = full dynamic range. */
  velToGain: number;
  /** Velocity layers crossfade over this many velocity steps at boundaries. */
  velCrossfade: number;
  zones: Zone[];
}

// ---------------------------------------------------------------------------
// Articulations and mics
// ---------------------------------------------------------------------------

export type ArticSelect =
  | { mode: 'always' }
  | { mode: 'keyswitch'; key: Midi }
  | { mode: 'cc'; cc: number; low: number; high: number }
  | { mode: 'velocity'; low: number; high: number };

export interface Articulation {
  id: string;
  name: string;
  select: ArticSelect;
}

export interface MicBus {
  id: string;
  name: string;
  gainDb: number;
  pan: number;
  /** Extra delay in ms to time-align a distant mic against the close one. */
  delayMs: number;
  muted: boolean;
}

// ---------------------------------------------------------------------------
// Instrument
// ---------------------------------------------------------------------------

export interface MasterSettings {
  gainDb: number;
  tuneCents: number;
  bendRangeSemis: number;
  /** 0 = unlimited. */
  polyphony: number;
  /** Exponent applied to normalised velocity. 1 = linear, <1 = louder soft. */
  velocityCurve: number;
  glideSeconds: number;
}

export interface Instrument {
  /** Format version, so old .sinst folders can be migrated. */
  version: 1;
  id: string;
  name: string;
  author: string;
  description: string;
  createdAt: number;
  modifiedAt: number;

  samples: Sample[];
  articulations: Articulation[];
  mics: MicBus[];
  groups: Group[];
  master: MasterSettings;

  /**
   * Capture settings, remembered with the project.
   *
   * Optional because it is filled in lazily by normalizeCapturePlan — a plan
   * references articulation and mic ids, so it can only be validated against
   * the instrument it belongs to, not constructed alongside it.
   */
  capture?: CapturePlan;
}

// ---------------------------------------------------------------------------
// Capture session planning
// ---------------------------------------------------------------------------

/** The matrix a guided capture session walks: notes × layers × round robins. */
export interface CapturePlan {
  lowNote: Midi;
  highNote: Midi;
  /** Semitones between sampled notes. 1 = chromatic. */
  step: number;
  velocityLayers: number;
  roundRobins: number;
  articulationId: string;
  micIds: string[];
  /** Seconds of silence that ends a take. */
  silenceTimeout: number;
  /** dBFS above the measured noise floor that starts a take. */
  onsetThresholdDb: number;
  /** Play a reference pitch before arming. */
  referenceTone: boolean;
  /**
   * What the reference is made of.
   *
   * 'recorded' repitches the nearest take you have already captured, which is
   * far easier to tune against than a sine — a pure tone gives the ear no
   * harmonic context, so its octave is ambiguous at the top and bottom of the
   * range, exactly where matching pitch is hardest. Falls back to 'sine' until
   * the session has captured something usable.
   */
  referenceSource: 'recorded' | 'preset';
  /** Which built-in tone to use, and what 'recorded' falls back to. */
  referencePreset: string;
}

export interface CaptureStep {
  index: number;
  midi: Midi;
  velLayer: number;
  rrIndex: number;
  micId: string;
  articulationId: string;
}

// ---------------------------------------------------------------------------
// Defaults
// ---------------------------------------------------------------------------

let idCounter = 0;
export const newId = (prefix: string): string =>
  `${prefix}_${Date.now().toString(36)}${(idCounter++).toString(36)}${Math.random()
    .toString(36)
    .slice(2, 6)}`;

export const defaultEnvelope = (): Envelope => ({
  attack: 0.001,
  decay: 0.3,
  sustain: 1,
  release: 0.25,
});

export const defaultFilter = (): FilterSettings => ({
  type: 'off',
  cutoff: 12000,
  resonance: 0.7,
  envAmount: 0,
  keyTrack: 0,
  velAmount: 0,
});

export const defaultMaster = (): MasterSettings => ({
  gainDb: 0,
  tuneCents: 0,
  bendRangeSemis: 2,
  polyphony: 0,
  velocityCurve: 1,
  glideSeconds: 0,
});

export const defaultLoop = (): Loop => ({ mode: 'off', start: 0, end: 0, crossfade: 0 });

export function createGroup(articulationId: string, name = 'Group'): Group {
  return {
    id: newId('grp'),
    name,
    articulationId,
    trigger: 'attack',
    roundRobin: 'randomNoRepeat',
    chokeGroup: 0,
    gainDb: 0,
    pan: 0,
    ampEnv: defaultEnvelope(),
    filter: defaultFilter(),
    filterEnv: defaultEnvelope(),
    velToGain: 1,
    velCrossfade: 0,
    zones: [],
  };
}

export function createInstrument(name = 'Untitled instrument'): Instrument {
  const artic: Articulation = { id: newId('art'), name: 'Sustain', select: { mode: 'always' } };
  const mic: MicBus = { id: newId('mic'), name: 'Close', gainDb: 0, pan: 0, delayMs: 0, muted: false };
  return {
    version: 1,
    id: newId('inst'),
    name,
    author: '',
    description: '',
    createdAt: Date.now(),
    modifiedAt: Date.now(),
    samples: [],
    articulations: [artic],
    mics: [mic],
    groups: [createGroup(artic.id, 'Sustain')],
    master: defaultMaster(),
  };
}
